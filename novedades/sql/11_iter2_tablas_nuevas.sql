MERGE INTO NEXOVOLT.NV_MOTIVO_ELIMINACION d
USING (
    SELECT 1 AS MOTIVO_ID, '14' AS CODIGO, 'HABEAS DATA (FALLO O TUTELA)' AS DESCRIPCION, 'S' AS CONFIRMADO FROM DUAL UNION ALL
    SELECT 2, '15', 'CADUCIDAD DE LA INFORMACION', 'S' FROM DUAL UNION ALL
    SELECT 3, '16', 'SUPLANTACION O FRAUDE', 'S' FROM DUAL UNION ALL
    SELECT 4, '17', 'ORDEN JUDICIAL O ADMINISTRATIVA', 'S' FROM DUAL UNION ALL
    SELECT 5, '18', 'PAGO TOTAL O SALDADA', 'S' FROM DUAL
) s
ON (d.CODIGO = s.CODIGO)
WHEN MATCHED THEN
    UPDATE SET d.DESCRIPCION = s.DESCRIPCION
WHEN NOT MATCHED THEN
    INSERT (MOTIVO_ID, CODIGO, DESCRIPCION, CONFIRMADO)
    VALUES (s.MOTIVO_ID, s.CODIGO, s.DESCRIPCION, s.CONFIRMADO);

