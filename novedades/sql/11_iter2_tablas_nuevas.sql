-- Ampliar CK_NV_CORTE_ESTADO para admitir ENVIADO_CON_INCONSISTENCIAS
BEGIN
    FOR r IN (
        SELECT constraint_name
        FROM all_constraints
        WHERE owner = 'NEXOVOLT'
          AND table_name = 'NV_CORTE'
          AND constraint_name = 'CK_NV_CORTE_ESTADO'
    ) LOOP
        EXECUTE IMMEDIATE 'ALTER TABLE NEXOVOLT.NV_CORTE DROP CONSTRAINT ' || r.constraint_name;
    END LOOP;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'ALTER TABLE NEXOVOLT.NV_CORTE ADD CONSTRAINT CK_NV_CORTE_ESTADO CHECK (ESTADO IN (''BORRADOR'', ''VALIDADO'', ''ENVIADO'', ''ENVIADO_CON_INCONSISTENCIAS'', ''RECHAZADO'', ''ANULADO''))';
EXCEPTION
    WHEN OTHERS THEN
        NULL;
END;
