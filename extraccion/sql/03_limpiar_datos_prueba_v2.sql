-- 1. Tablas dependientes de NEXOVOLT
DELETE FROM NEXOVOLT.NV_ELIMINACION
 WHERE ELIMINACION_ID = 9001
    OR OBLIGACION_ID IN (SELECT OBLIGACION_ID FROM NEXOVOLT.NV_OBLIGACION WHERE CLIENTE_ID BETWEEN 900101 AND 900118);

DELETE FROM NEXOVOLT.NV_MARCA_CASTIGO
 WHERE CLIENTE_ID BETWEEN 900101 AND 900118;

DELETE FROM NEXOVOLT.NV_REPORTE_DETALLE
 WHERE CORTE_ID = 901
    OR CLIENTE_ID BETWEEN 900101 AND 900118;

DELETE FROM NEXOVOLT.NV_CORTE_VALIDACION
 WHERE CORTE_ID = 901;

DELETE FROM NEXOVOLT.NV_CORTE_USUARIO
 WHERE CORTE_ID = 901;

DELETE FROM NEXOVOLT.NV_CORTE
 WHERE CORTE_ID = 901;

DELETE FROM NEXOVOLT.NV_OBLIGACION
 WHERE CLIENTE_ID BETWEEN 900101 AND 900118
    OR OBLIGACION_ID BETWEEN 900101 AND 900118;

DELETE FROM NEXOVOLT.NV_TITULAR
 WHERE CLIENTE_ID BETWEEN 900101 AND 900118
    OR TITULAR_ID BETWEEN 900101 AND 900118;

-- 2. Tablas del esquema SAC
DELETE FROM SAC.CLI_PAGOS
 WHERE CLIENTE_ID BETWEEN 900101 AND 900118
    OR NUMERO_PROCESO IN (100101, 100102, 100103, 100104, 100105, 100106, 100107, 100108, 100109, 100110, 100111, 100112, 100113, 100114, 100115, 100116, 100117, 100118, 100119, 100120, -9876543210);

DELETE FROM SAC.CLI_FACTURACION
 WHERE CLIENTE_ID BETWEEN 900101 AND 900118
    OR NUMERO_PROCESO IN (100101, 100102, 100103, 100104, 100105, 100106, 100107, 100108, 100109, 100110, 100111, 100112, 100113, 100114, 100115, 100116, 100117, 100118, 100119, 100120, -9876543210);

DELETE FROM SAC.CREDITOS
 WHERE CLIENTE_ID BETWEEN 900101 AND 900118;

DELETE FROM SAC.CLIENTES
 WHERE CLIENTE_ID BETWEEN 900101 AND 900118;

COMMIT;
