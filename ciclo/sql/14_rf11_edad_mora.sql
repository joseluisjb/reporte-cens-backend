-- ── EDAD_ANTERIOR ─────────────────────────────────────────────────────────────
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
    FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'NEXOVOLT' AND TABLE_NAME = 'NV_REPORTE_DETALLE'
      AND COLUMN_NAME = 'EDAD_ANTERIOR';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE
            'ALTER TABLE NEXOVOLT.NV_REPORTE_DETALLE ADD (EDAD_ANTERIOR VARCHAR2(2))';
    END IF;
END;
/

