/* NexoVolt - 15 Columnas RF14 (caducado en el SAC) en NV_REPORTE_DETALLE
   Agrega CADUCADO y ATRASOS_PERMITIDOS, que copia la extraccion desde
   V_CALCULO_CORTE (columnas que el DBA anade en el script de RF14).
   Es seguro repetirlo: comprueba ALL_TAB_COLUMNS antes de cada ALTER TABLE.

   Reversa:
     ALTER TABLE NEXOVOLT.NV_REPORTE_DETALLE DROP COLUMN ATRASOS_PERMITIDOS;
     ALTER TABLE NEXOVOLT.NV_REPORTE_DETALLE DROP COLUMN CADUCADO;

   Verificacion:
     SELECT COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE
     FROM ALL_TAB_COLUMNS
     WHERE OWNER = 'NEXOVOLT' AND TABLE_NAME = 'NV_REPORTE_DETALLE'
       AND COLUMN_NAME IN ('CADUCADO', 'ATRASOS_PERMITIDOS')
     ORDER BY COLUMN_NAME;
*/

-- CADUCADO: S cuando CONTATRASOS >= ATRASOS_PERMITIDOS en el SAC (RF14)
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
    FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'NEXOVOLT' AND TABLE_NAME = 'NV_REPORTE_DETALLE'
      AND COLUMN_NAME = 'CADUCADO';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE
            'ALTER TABLE NEXOVOLT.NV_REPORTE_DETALLE '
            'ADD (CADUCADO CHAR(1) DEFAULT ''N'' NOT NULL)';
    END IF;
END;
/

-- ATRASOS_PERMITIDOS: tope de cuotas atrasadas antes de la caducidad (RF14)
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
    FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'NEXOVOLT' AND TABLE_NAME = 'NV_REPORTE_DETALLE'
      AND COLUMN_NAME = 'ATRASOS_PERMITIDOS';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE
            'ALTER TABLE NEXOVOLT.NV_REPORTE_DETALLE '
            'ADD (ATRASOS_PERMITIDOS NUMBER(5))';
    END IF;
END;
/

-- Verificacion
SELECT COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE
FROM ALL_TAB_COLUMNS
WHERE OWNER = 'NEXOVOLT' AND TABLE_NAME = 'NV_REPORTE_DETALLE'
  AND COLUMN_NAME IN ('CADUCADO', 'ATRASOS_PERMITIDOS')
ORDER BY COLUMN_NAME;
