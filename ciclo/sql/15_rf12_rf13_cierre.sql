BEGIN
    SELECT COUNT(*) INTO v_count FROM ALL_TAB_COLUMNS
    WHERE OWNER = 'NEXOVOLT' AND TABLE_NAME = 'NV_REPORTE_DETALLE'
      AND COLUMN_NAME = 'FECHA_PAGO';
