-- Esquema PostgreSQL propuesto para RF6/RF8.
-- Separado de Oracle; no ejecuta ni crea objetos en la base de CENS.
-- usuario_id queda sin FK hasta acordar el contrato con el servicio de usuarios.

CREATE TABLE IF NOT EXISTS nv_historial_reporte (
    reporte_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_corte DATE NOT NULL,
    tipo_reporte VARCHAR(2) NOT NULL,
    estado VARCHAR(10) NOT NULL
        CHECK (estado IN ('BORRADOR', 'VALIDADO', 'ENVIADO', 'ANULADO')),
    generado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    enviado_en TIMESTAMPTZ,
    usuario_id BIGINT,
    total_registros INTEGER NOT NULL DEFAULT 0 CHECK (total_registros >= 0),
    saldo_consolidado NUMERIC(14, 0) NOT NULL DEFAULT 0
        CHECK (saldo_consolidado >= 0),
    conceptos_usados JSONB NOT NULL DEFAULT '[]'::jsonb
        CHECK (jsonb_typeof(conceptos_usados) = 'array'),
    CHECK (enviado_en IS NULL OR enviado_en >= generado_en)
);

CREATE TABLE IF NOT EXISTS nv_deudor (
    obligacion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL,
    numero_proceso BIGINT NOT NULL,
    numero_obligacion_tu VARCHAR(20) NOT NULL UNIQUE,
    fecha_inicio DATE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (cliente_id, numero_proceso)
);

CREATE TABLE IF NOT EXISTS nv_historial_deudor (
    historial_deudor_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporte_id BIGINT NOT NULL
        REFERENCES nv_historial_reporte (reporte_id) ON DELETE RESTRICT,
    obligacion_id BIGINT NOT NULL
        REFERENCES nv_deudor (obligacion_id) ON DELETE RESTRICT,
    estado_tu VARCHAR(2),
    edad_mora VARCHAR(2) CHECK (
        edad_mora IS NULL OR edad_mora IN
        ('00', '01', '02', '03', '04', '05', '06', '07',
         '08', '09', '10', '11', '12', '13', '14')
    ),
    dias_mora INTEGER CHECK (dias_mora IS NULL OR dias_mora >= 0),
    fecha_limite_pago DATE,
    valor_inicial NUMERIC(14, 0) CHECK (valor_inicial IS NULL OR valor_inicial >= 0),
    valor_mora NUMERIC(14, 0) CHECK (valor_mora IS NULL OR valor_mora >= 0),
    valor_saldo NUMERIC(14, 0) NOT NULL CHECK (valor_saldo >= 0),
    valor_cuota NUMERIC(14, 0) CHECK (valor_cuota IS NULL OR valor_cuota >= 0),
    numero_creditos INTEGER NOT NULL DEFAULT 1 CHECK (numero_creditos > 0),
    fecha_ultimo_pago DATE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (reporte_id, obligacion_id)
);

CREATE INDEX IF NOT EXISTS ix_nv_historial_reporte_fecha_estado
    ON nv_historial_reporte (fecha_corte DESC, estado);

CREATE INDEX IF NOT EXISTS ix_nv_historial_deudor_obligacion_reporte
    ON nv_historial_deudor (obligacion_id, reporte_id DESC);

CREATE INDEX IF NOT EXISTS ix_nv_historial_deudor_reporte
    ON nv_historial_deudor (reporte_id);
