-- 1. Verificacion de existencia de las tablas creadas
SELECT TABLE_NAME, STATUS, NUM_ROWS
FROM ALL_TABLES
WHERE OWNER = 'NEXOVOLT'
  AND TABLE_NAME IN (
      'NV_ARCHIVO', 'NV_CARGUE_RESULTADO', 'NV_CARGUE_INCONSISTENCIA',
      'NV_NATURALEZA_REESTR', 'NV_REFINANCIACION', 'NV_MARCA_CASTIGO',
      'NV_TIPOLOGIA_RECLAMO', 'NV_RECLAMO', 'NV_MOTIVO_ELIMINACION',
      'NV_NOVEDAD', 'NV_ELIMINACION', 'NV_RECTIFICACION'
  )
ORDER BY TABLE_NAME;

-- 2. Verificacion de columnas de cada tabla
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE, DATA_DEFAULT
FROM ALL_TAB_COLUMNS
WHERE OWNER = 'NEXOVOLT'
  AND TABLE_NAME IN (
      'NV_ARCHIVO', 'NV_CARGUE_RESULTADO', 'NV_CARGUE_INCONSISTENCIA',
      'NV_NATURALEZA_REESTR', 'NV_REFINANCIACION', 'NV_MARCA_CASTIGO',
      'NV_TIPOLOGIA_RECLAMO', 'NV_RECLAMO', 'NV_MOTIVO_ELIMINACION',
      'NV_NOVEDAD', 'NV_ELIMINACION', 'NV_RECTIFICACION'
  )
ORDER BY TABLE_NAME, COLUMN_ID;

-- 3. Verificacion de llaves primarias y foraneas
SELECT c.TABLE_NAME, c.CONSTRAINT_NAME, c.CONSTRAINT_TYPE, c.R_CONSTRAINT_NAME, c.STATUS
FROM ALL_CONSTRAINTS c
WHERE c.OWNER = 'NEXOVOLT'
  AND c.TABLE_NAME IN (
      'NV_ARCHIVO', 'NV_CARGUE_RESULTADO', 'NV_CARGUE_INCONSISTENCIA',
      'NV_NATURALEZA_REESTR', 'NV_REFINANCIACION', 'NV_MARCA_CASTIGO',
      'NV_TIPOLOGIA_RECLAMO', 'NV_RECLAMO', 'NV_MOTIVO_ELIMINACION',
      'NV_NOVEDAD', 'NV_ELIMINACION', 'NV_RECTIFICACION'
  )
ORDER BY c.TABLE_NAME, c.CONSTRAINT_TYPE;

-- 4. Verificacion de indices especiales (parciales y de soporte)
SELECT INDEX_NAME, TABLE_NAME, UNIQUENESS, STATUS
FROM ALL_INDEXES
WHERE OWNER = 'NEXOVOLT'
  AND TABLE_NAME IN (
      'NV_ARCHIVO', 'NV_CARGUE_RESULTADO', 'NV_CARGUE_INCONSISTENCIA',
      'NV_NATURALEZA_REESTR', 'NV_REFINANCIACION', 'NV_MARCA_CASTIGO',
      'NV_TIPOLOGIA_RECLAMO', 'NV_RECLAMO', 'NV_MOTIVO_ELIMINACION',
      'NV_NOVEDAD', 'NV_ELIMINACION', 'NV_RECTIFICACION'
  )
ORDER BY TABLE_NAME, INDEX_NAME;

-- 5. Verificacion de secuencias creadas
SELECT SEQUENCE_NAME, MIN_VALUE, MAX_VALUE, INCREMENT_BY, LAST_NUMBER
FROM ALL_SEQUENCES
WHERE SEQUENCE_OWNER = 'NEXOVOLT'
  AND SEQUENCE_NAME LIKE 'SEQ_NV_%'
ORDER BY SEQUENCE_NAME;

-- 6. Verificacion de catalogos inicializados (semillas)
SELECT 'NV_MOTIVO_ELIMINACION' AS CATALOGO, CODIGO, DESCRIPCION, CONFIRMADO FROM NEXOVOLT.NV_MOTIVO_ELIMINACION
UNION ALL
SELECT 'NV_TIPOLOGIA_RECLAMO', CODIGO, DESCRIPCION, CONFIRMADO FROM NEXOVOLT.NV_TIPOLOGIA_RECLAMO
UNION ALL
SELECT 'NV_NATURALEZA_REESTR', CODIGO, DESCRIPCION, CONFIRMADO FROM NEXOVOLT.NV_NATURALEZA_REESTR
ORDER BY 1, 2;
